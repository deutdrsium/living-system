"""Bundle the life workspace for AstrBot's sandboxed plugin-page iframe."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "plugins" / "astrbot_plugin_good_life" / "pages" / "我会去好好生活"


def build():
    workspace = PAGE / "life"
    html = (workspace / "index.html").read_text(encoding="utf-8-sig")
    css = (workspace / "style.css").read_text(encoding="utf-8-sig")
    bridge = (workspace / "embedded-bridge.js").read_text(encoding="utf-8-sig")
    app = (workspace / "app.js").read_text(encoding="utf-8-sig")
    html = html.replace('<link rel="stylesheet" href="style.css">', '<style>' + css + '</style>')
    html = html.replace('<script src="embedded-bridge.js" defer></script>', '')
    html = html.replace('<script src="app.js" defer></script>', '')
    scripts = (bridge + "\n" + app).replace("</script", "<\\/script")
    html = html.replace("</body>", "<script>" + scripts + "</script></body>")
    return ("// Generated by tools/sync_life_workspace.py; edit life/ sources instead.\n"
            "window.GoodLifeWorkspace=" + json.dumps(html, ensure_ascii=False) + ";\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = PAGE / "life-bundle.js"
    content = build()
    changed = not target.exists() or target.read_bytes() != content
    if changed and not args.check:
        target.write_bytes(content)
    print("workspace bundle " + ("needs update" if changed and args.check else "ready"))
    return int(args.check and changed)


if __name__ == "__main__":
    raise SystemExit(main())
